# turns: 用户说的话序列；reply_turns 内有多轮就多轮聊
SCENARIOS = []
_sid = [0]


def _add(cat, char, turns, tags=()):
    # 归一化：turns 允许是字符串（单轮）或列表（多轮），绝不能被按字符迭代
    if isinstance(turns, str):
        turns = [turns]
    _sid[0] += 1
    SCENARIOS.append({
        "id": f"s{_sid[0]:03d}", "cat": cat, "char": char, "turns": list(turns), "tags": list(tags),
    })


