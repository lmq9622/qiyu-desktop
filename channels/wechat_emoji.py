def convert_emoji_tags(text: str) -> str:
    """把回复里的 [表情名] 换成标准 emoji 字符。

    ⚠️ 认不出的也要去掉方括号、保留里面的字，不再整段丢掉。
    原来认不出返回 ""（丢掉），会把句子咬掉一块（"我好[委屈]" → "我好"），
    而且提示词里提到的 [抱抱] 恰好不在表里 → 真被吃掉过。
    现在的三级兜底：精确映射 → 别名 → 去括号保文字。最后一级保证"绝不剩 []"。
    """
    if not text or "[" not in text:
        return text

    def _sub(m):
        name = (m.group(1) or "").strip()
        ch = WECHAT_EMOJI_CHARS.get(name) or WECHAT_EMOJI_ALIASES.get(name)
        return ch or name            # ← 认不出：去括号、保文字（不再丢）

    return re.sub(r"\[([^\[\]]{1,8})\]", _sub, str(text))


